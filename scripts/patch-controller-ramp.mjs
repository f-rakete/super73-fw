#!/usr/bin/env node
// Patch the GD32 controller `410` image to soften the throttle dead-start ramp.
//
// Scope: ONLY the off-road modes (3 US / 7 EU) per-mode throttle ramp step. This does
// NOT touch any speed cap, the 25 km/h (0x9c4) clamp, road-legal mode 4, or pedal-assist.
// It changes how quickly the *throttle* demand climbs toward its target from a dead start,
// i.e. launch smoothness, not top speed or power.
//
// Evidence: docs/throttle-ramp.md, work/ghidra/controller-insn.txt, controller-dump.txt.
// The ramp field is *(DAT_08006778+0x14); each control tick it moves toward the throttle
// target by the per-mode step. Stock step = 110 (standstill) / 70 (rolling). Ramp time to
// full is linear in 1/step, independent of the (unmeasured) control-loop rate.
//
// Usage:
//   node tools/patch-controller-ramp.mjs [--standstill N] [--rolling N] [--out DIR]
//   N is the imm8 step, 1..255. Lower = softer/slower launch. Omit to use defaults.

import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC_DIR = join(ROOT, "work", "firmware", "controller-410-stock");
const BIN = "GD_S73Rx_H104_S410EU_20221020.bin";
const DAT = "GD_S73Rx_H104_S410EU_20221020.dat";
const LOAD_BASE = 0x08003000;
const STOCK_SHA256 = "c8d4aba4bbcbb8e5178c841580ce13bc4b97141b5c87b59e5b1cfd99650234ab";

// Verified patch points. fileOff = instrAddr - LOAD_BASE (imm8 is the first byte of `movs`).
const POINTS = {
  m3_standstill: { off: 0x2e4e, stock: 0x6e, addr: 0x08005e4e },
  m3_rolling:    { off: 0x2e52, stock: 0x46, addr: 0x08005e52 },
  m7_standstill: { off: 0x30f0, stock: 0x6e, addr: 0x080060f0 },
  m7_rolling:    { off: 0x30f4, stock: 0x46, addr: 0x080060f4 },
};

function arg(name, def) {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : def;
}
function step(name, def) {
  const v = Number(arg(name, def));
  if (!Number.isInteger(v) || v < 1 || v > 255)
    throw new Error(`--${name} must be an integer 1..255 (got ${arg(name, def)})`);
  return v;
}
const sha = (b) => createHash("sha256").update(b).digest("hex");

const standstill = step("standstill", "12");
const rolling = step("rolling", "24");
const outDir = join(ROOT, "work", "firmware", arg("out", "controller-410-rampmod"));

const bin = readFileSync(join(SRC_DIR, BIN));
if (sha(bin) !== STOCK_SHA256) {
  console.error(`REFUSING: base image sha256 ${sha(bin)} != known stock ${STOCK_SHA256}.`);
  process.exit(1);
}
for (const [name, p] of Object.entries(POINTS)) {
  if (bin[p.off] !== p.stock)
    throw new Error(`guard: ${name} @0x${p.off.toString(16)} is 0x${bin[p.off].toString(16)}, expected 0x${p.stock.toString(16)}`);
}

const newVals = {
  m3_standstill: standstill, m7_standstill: standstill,
  m3_rolling: rolling,       m7_rolling: rolling,
};
const out = Buffer.from(bin);
for (const [name, p] of Object.entries(POINTS)) out[p.off] = newVals[name];

mkdirSync(outDir, { recursive: true });
const outBin = join(outDir, BIN);
writeFileSync(outBin, out);
copyFileSync(join(SRC_DIR, DAT), join(outDir, DAT)); // kept for reference; signature is now STALE

// Timing model (from docs/throttle-ramp.md): cycles-to-full = ceil(1250/step); linear in 1/step.
const rates = [500, 1000, 2000, 8000, 16000];
const msToFull = (s, hz) => ((Math.ceil(1250 / s) / hz) * 1000).toFixed(1);
const timing = (label, s) =>
  `${label} (step ${s}): ` + rates.map((hz) => `${hz}Hz=${msToFull(s, hz)}ms`).join("  ");

const notes = `# controller-410 ramp-mod build

Generated by scripts/patch-controller-ramp.mjs. Off-road throttle dead-start ramp only.

## What changed (4 bytes)
| point | file off | stock | new |
|---|---|---|---|
| mode 3 standstill | 0x2e4e | 110 | ${standstill} |
| mode 3 rolling    | 0x2e52 | 70  | ${rolling} |
| mode 7 standstill | 0x30f0 | 110 | ${standstill} |
| mode 7 rolling    | 0x30f4 | 70  | ${rolling} |

Speed caps, the 0x9c4 (25 km/h) clamp, road-legal mode 4, and pedal-assist are untouched.

## Hashes
- stock .bin sha256: ${STOCK_SHA256}
- patched .bin sha256: ${sha(out)}

## Estimated time for throttle demand 0 -> operational full (~1250), linear in 1/step
- ${timing("standstill", standstill)}
- ${timing("rolling", rolling)}
- (stock for reference) ${timing("standstill", 110)}

Control-loop rate is not yet pinned from static RE (see docs/throttle-ramp.md). The *relative*
change is exact regardless of rate; only the absolute ms depends on it. Bench-measure to convert.

## DEPLOY CAVEAT (unresolved — read before flashing)
The paired ${DAT} is a Nordic Secure-DFU **signed init packet**: 32-byte SHA-256 of the STOCK
image + a 64-byte ECDSA P-256 signature. It is image-specific and now MISMATCHES this patched
.bin; it cannot be re-signed without Comodule's private key. This package is therefore only
flashable via a path that does NOT verify that signature against the controller image
(e.g. reverse.bike's flasher / SWD). Whether the stock display's ext1/CAN push enforces it is
the open question from the audit — confirm before relying on an over-BT flash.
`;
writeFileSync(join(outDir, "NOTES.md"), notes);

console.log(`stock   sha256: ${STOCK_SHA256}`);
console.log(`patched sha256: ${sha(out)}`);
console.log(`steps: standstill 110->${standstill}, rolling 70->${rolling}`);
console.log(`wrote: ${outBin}`);
console.log(`notes: ${join(outDir, "NOTES.md")}`);
